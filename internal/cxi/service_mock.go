package cxi

import (
	"fmt"
	"os"
	"slices"
	"sync"
	"sync/atomic"
)

type MockServiceManager struct{}

var _ ServiceManager = MockServiceManager{}

const mockServiceDir = "/tmp/cxi-services"

// mockSvcIDCounter hands out unique svc_ids so mock mode mirrors the kernel's
// per-service id allocation. MockServiceManager is a stateless value type, so
// the counter lives at package scope. First CreateService returns 1.
var mockSvcIDCounter int64

// SeedMockSvcIDCounter sets the mock svc_id counter so the next CreateService
// returns base+1. The NRI plugin seeds it past the highest blessed
// --system-svc-id in mock mode so generated service ids never collide with the
// reserved system services. No-op equivalent to the default when base is 0.
func SeedMockSvcIDCounter(base int64) {
	atomic.StoreInt64(&mockSvcIDCounter, base)
}

func (MockServiceManager) CreateService(deviceName string, netnsInode uint64, vni int, resources ResourceSet) (int, error) {
	if err := os.MkdirAll(mockServiceDir, 0o755); err != nil {
		return 0, fmt.Errorf("creating mock service dir: %w", err)
	}
	yaml := fmt.Sprintf(`# CXI service for device %s
# Generated by cxi-dra-driver (mock mode)
# Apply on real hardware with: cxi_service create -y <this file>
resource_limits: 1
restricted_members: 1
restricted_tcs: 0
exclusive_cp: 0
limits:
  - name: ACs
    max: %d
    res: %d
  - name: CTs
    max: %d
    res: %d
  - name: EQs
    max: %d
    res: %d
  - name: LEs
    max: %d
    res: %d
  - name: PTEs
    max: %d
    res: %d
  - name: TGQs
    max: %d
    res: %d
  - name: TXQs
    max: %d
    res: %d
  - name: TLEs
    max: %d
    res: %d
vnis:
  vni: %d
members:
  - type: netns
    id: %d
`,
		deviceName,
		resources.ACs, resources.ACs,
		resources.CTs, resources.CTs,
		resources.EQs, resources.EQs,
		resources.LEs, resources.LEs,
		resources.PTEs, resources.PTEs,
		resources.TGQs, resources.TGQs,
		resources.TXQs, resources.TXQs,
		resources.TLEs, resources.TLEs,
		vni, netnsInode)
	svcID := int(atomic.AddInt64(&mockSvcIDCounter, 1))
	path := MockServicePath(deviceName, svcID)
	if err := os.WriteFile(path, []byte(yaml), 0o644); err != nil {
		return 0, fmt.Errorf("writing mock service file %s: %w", path, err)
	}
	fmt.Printf("cxi-mock: wrote CXI service file: %s\n", path)
	return svcID, nil
}
func (MockServiceManager) DeleteService(deviceName string, svcID int) error {
	path := MockServicePath(deviceName, svcID)
	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("removing mock service file %s: %w", path, err)
	}
	fmt.Printf("cxi-mock: removed CXI service file: %s\n", path)
	return nil
}
func MockServicePath(deviceName string, svcID int) string {
	return fmt.Sprintf("%s/%s-%d.yaml", mockServiceDir, deviceName, svcID)
}

// MockParent is one parent service on a mock PF.
type MockParent struct {
	PFName     string // e.g. "cxi0"
	SvcID      int    // service id on the PF
	Descriptor ParentDescriptor
}

// MockTopology is the in-memory VF topology behind the parent read path
// (ReadParentBudget, ReadParentRemaining, ReadVFSystemReservation) in non-cxi
// builds. Parent→VF assignment is not stored here: callers pass the VF names,
// exactly as they do against real hardware.
type MockTopology struct {
	Parents    []MockParent
	VFServices map[string][]ServiceReservation // keyed by VF device name, e.g. "cxi4"
}

var (
	mockTopologyMu sync.RWMutex
	mockTopology   MockTopology
)

// SetMockTopology installs the topology the mock parent reads answer from.
func SetMockTopology(t MockTopology) {
	mockTopologyMu.Lock()
	defer mockTopologyMu.Unlock()
	mockTopology = t
}

// ResetMockTopology clears the mock topology.
func ResetMockTopology() {
	SetMockTopology(MockTopology{})
}

// MockParentDescriptor returns the mock parent svcID on pfName, or an error if
// the topology has none — the mock counterpart of cxil_get_svc failing.
func MockParentDescriptor(pfName string, svcID int) (ParentDescriptor, error) {
	mockTopologyMu.RLock()
	defer mockTopologyMu.RUnlock()
	for _, p := range mockTopology.Parents {
		if p.PFName == pfName && p.SvcID == svcID {
			return p.Descriptor, nil
		}
	}
	return ParentDescriptor{}, fmt.Errorf("cxi-mock: no parent svc %d on %s", svcID, pfName)
}

// MockVFServices returns a copy of the mock service list of the VF vfName; a VF
// the topology does not mention has no services.
func MockVFServices(vfName string) []ServiceReservation {
	mockTopologyMu.RLock()
	defer mockTopologyMu.RUnlock()
	return slices.Clone(mockTopology.VFServices[vfName])
}
